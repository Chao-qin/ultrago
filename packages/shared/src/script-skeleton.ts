/**
 * The program around an inline script node's body.
 *
 * A script node used to be a command line pointing at a file, so its author
 * wrote the whole program — including the part that reads stdin, parses it,
 * and prints the result on the last line. That boilerplate is the same every
 * time and getting it subtly wrong (printing before the result, forgetting the
 * newline, dumping non-JSON) is indistinguishable from the node being broken.
 *
 * So the node stores only a BODY, and this module supplies everything around
 * it: the signature, derived from the declared contracts, and the read/write
 * that the runner's stdin/last-line-of-stdout protocol requires. The editor
 * shows the same header and footer as read-only text, which is what makes the
 * shape of `params` answerable by looking rather than by asking.
 *
 * NOT REUSED FROM `codegen.ts`, which has a near-identical
 * `schemaValueToTsType`, for two concrete reasons: that module ends in a
 * top-level `main()` and so cannot be imported without running the book
 * generator, and its fallback returns `"string"` for anything it does not
 * recognise — including a `$ref`, which is how a document whose fields live
 * behind a reference silently becomes a string. This one says `unknown`
 * instead, and says why in a comment the author can read.
 */
import { unsupportedSchemaKeywords } from "./schema-keywords.js";
import type { ParamSchemaFragment } from "./param-runtime.js";

/**
 * The languages an inline body may be written in — TypeScript, and only
 * TypeScript.
 *
 * Not a preference, but not about distrusting the OPERATOR either — whoever can
 * open this panel already has a shell on the same machine, so a sandbox that
 * only protected against them would protect against nothing. The thing it
 * guards is provenance: an inline body is frequently pasted from somewhere or
 * generated by a model, so the person running it is often not the person who
 * wrote it. Node's own permission model (`--permission`) contains that on
 * macOS, Linux and Windows alike at no dependency cost, turning "this snippet
 * quietly read ~/.ssh" into "it cannot reach the filesystem" — while a spawned
 * `python3` is a separate process holding the console user's full rights, with
 * no cross-platform way to contain it short of Docker.
 *
 * "Contains" is not "seals": the network is NOT covered on Node 22, which is
 * stated wherever an author can see it rather than left for them to discover.
 * See `interpreterFor` in the runner for what is and is not blocked.
 *
 * Python has NOT gone away: a `command` node still runs it. That code lives in
 * a reviewed file in the repository, which is a different trust class than
 * something typed into a box, and needs no sandbox for the same reason the
 * repository's own scripts do not.
 */
export const SCRIPT_LANGUAGES = ["ts"] as const;
export type ScriptLanguage = (typeof SCRIPT_LANGUAGES)[number];

export const SCRIPT_LANGUAGE_LABELS: Record<ScriptLanguage, string> = {
  ts: "TypeScript",
};

/** File extension the body is materialised under, which is also what decides
 *  how the interpreter parses it. */
export const SCRIPT_EXTENSION: Record<ScriptLanguage, string> = {
  ts: "ts",
};

/** The read-only text above and below the editable body. `header` ends with the
 *  line that opens `handler`, so the body is written at one level of
 *  indentation. */
export interface ScriptSkeleton {
  header: string;
  footer: string;
  /** What one level of indentation is, so the body can be re-indented into the
   *  header without the caller guessing. */
  indent: string;
}

const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function isObject(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function asSchema(value: unknown): ParamSchemaFragment {
  return isObject(value) ? (value as ParamSchemaFragment) : {};
}

/**
 * A schema as a TypeScript type.
 *
 * `unknown` — never `string` — for anything outside the subset this repo's
 * validator implements. A generated type that claims more than the validator
 * can check is a type that lies at compile time about a value nobody checked at
 * run time, which is the same defect `validateOutput` was fixed for.
 */
export function schemaToTs(schema: ParamSchemaFragment | null | undefined): string {
  if (!schema || !isObject(schema)) return "unknown";
  if (unsupportedSchemaKeywords(schema).length > 0) return "unknown";
  return renderTs(schema);
}

function renderTs(s: ParamSchemaFragment): string {
  if (Array.isArray(s.enum) && s.enum.length > 0) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (s.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${renderTs(asSchema(s.items))}[]`;
    case "object": {
      if (!isObject(s.properties)) return "Record<string, unknown>";
      const required = new Set(Array.isArray(s.required) ? s.required.filter((v): v is string => typeof v === "string") : []);
      const fields = Object.entries(s.properties).map(([name, raw]) => {
        const key = IDENTIFIER_RE.test(name) ? name : JSON.stringify(name);
        return `${key}${required.has(name) ? "" : "?"}: ${renderTs(asSchema(raw))}`;
      });
      return fields.length > 0 ? `{ ${fields.join("; ")} }` : "Record<string, unknown>";
    }
    default:
      // No `type` at all — undeclared, not "a string". Same rule as above.
      return "unknown";
  }
}

/** The declared fields as `name: type` comment lines, so the author can read
 *  what `params` holds without leaving the editor. Empty when nothing is
 *  declared, which is itself the honest answer. */
function fieldLines(schema: ParamSchemaFragment | null | undefined): string[] {
  if (!schema || !isObject(schema) || !isObject(schema.properties)) return [];
  const required = new Set(Array.isArray(schema.required) ? schema.required.filter((v): v is string => typeof v === "string") : []);
  return Object.entries(schema.properties).map(
    ([name, raw]) => `${name}: ${renderTs(asSchema(raw))}${required.has(name) ? "" : "（可选）"}`,
  );
}

const UNDECLARED_INPUT_NOTE = "入参契约未声明，params 里有什么取决于连线";
const UNDECLARED_OUTPUT_NOTE = "产出契约未声明，返回什么都不会被校验";

/**
 * Everything around the body.
 *
 * The footer is the whole reason the author no longer writes it: the runner
 * takes the LAST LINE of stdout as the result, so the result must be preceded
 * by a newline (a script that logged without a trailing newline would otherwise
 * have its last log line glued to its result) and must be the last thing
 * written. Getting that wrong looks exactly like a script that produced nothing.
 */
export function scriptSkeleton(
  language: ScriptLanguage,
  inputSchema: ParamSchemaFragment | null,
  outputSchema: ParamSchemaFragment | null,
): ScriptSkeleton {
  const inputs = fieldLines(inputSchema);

  const paramsType = schemaToTs(inputSchema);
  const resultType = schemaToTs(outputSchema);
  return {
    indent: "  ",
    header: [
      `type Params = ${paramsType === "unknown" ? "Record<string, unknown>" : paramsType};`,
      `type Result = ${resultType};`,
      "",
      inputs.length > 0
        ? "// params 就是 stdin 里的那个对象，字段见上面的 Params。"
        : `// ${UNDECLARED_INPUT_NOTE}。`,
      // Two things an author WILL trip over otherwise, and both cost one line
      // to say: the body sits inside a function, so a top-level `import`
      // statement is a syntax error there; and the sandbox denies the
      // filesystem and child processes but NOT the network, which is the one
      // asymmetry someone reading "sandboxed" would otherwise get wrong.
      "// 要引模块用 await import(\"…\")；顶层 import 在函数体里是语法错误。",
      "// 沙箱封掉了文件、子进程；网络没封（Node 22 没有网络权限档），别把敏感入参发出去。",
      "async function handler(params: Params): Promise<Result> {",
    ].join("\n"),
    footer: [
      "}",
      "",
      "const _chunks: Buffer[] = [];",
      'process.stdin.on("data", (c: Buffer) => _chunks.push(c));',
      'process.stdin.on("end", async () => {',
      '  const _result = await handler(JSON.parse(Buffer.concat(_chunks).toString("utf8")));',
      // Same leading newline, same reason.
      '  process.stdout.write("\\n" + JSON.stringify(_result));',
      "});",
    ].join("\n"),
  };
}

/**
 * The body re-indented into the skeleton — the exact text that gets written to
 * disk and run.
 *
 * Uniform indentation, so a body's own nesting survives: the author writes at
 * column 0 and every line shifts by the same amount. Blank lines are left
 * blank rather than filled with spaces, because trailing whitespace is noise in
 * an editor and worse in a diff.
 *
 * An empty body still has to produce a syntactically valid program, hence the
 * language's own "do nothing" statement — otherwise a node the author has not
 * filled in yet fails with a parse error instead of an empty result.
 */
export function buildScriptSource(
  language: ScriptLanguage,
  body: string,
  inputSchema: ParamSchemaFragment | null,
  outputSchema: ParamSchemaFragment | null,
): string {
  const skeleton = scriptSkeleton(language, inputSchema, outputSchema);
  const lines = body.replace(/\r\n/g, "\n").split("\n");
  const meaningful = lines.some((l) => l.trim().length > 0);
  const indented = (meaningful ? lines : ["return {} as Result"])
    .map((line) => (line.trim().length === 0 ? "" : skeleton.indent + line))
    .join("\n");
  return `${skeleton.header}\n${indented}\n${skeleton.footer}\n`;
}
